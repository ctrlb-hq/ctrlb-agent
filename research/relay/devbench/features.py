DATA_DIRS = {'readtime': ('samples',), 'hone': ('data_file', 'examples')}


def apply(root, edits):
    C.apply(root, edits)


def tree_copy(project):
    tmp = tempfile.mkdtemp(prefix=f'devbench-feat-{project}-')
    shutil.copytree(os.path.join(T.set_dir(project), 'tree'), tmp, dirs_exist_ok=True)
    return tmp


def scrub_check(project):
    """Apply the questions edits to a copy of the tree; list every file (but data) still matching a pattern."""
    q = FEATURES[project]['questions']
    tmp = tree_copy(project)
    apply(tmp, q['edits'])
    hits = []
    for d, _, files in os.walk(tmp):
        for f in files:
            rel = os.path.relpath(os.path.join(d, f), tmp)
            if rel.split('/')[0] in DATA_DIRS[project] and not rel.endswith(('.md', '.py', '.sh')):
                continue  # data files (csv/json/html/txt): values, not documents
            with open(os.path.join(d, f), errors='replace') as fh:
                text = fh.read()
            hits += [f'{rel}: {m.group(0)!r}' for p in q['scrub_patterns'] for m in re.finditer(p, text)]
    shutil.rmtree(tmp, ignore_errors=True)
    return hits


def build_judge(project):
    """A counterfactual judge (questions.judge): the reference judge with questions.judge_edits applied."""
    q = FEATURES[project]['questions']
    d = os.path.join(T.set_dir(project), q['judge'])
    tmp = d + '.tmp'
    shutil.rmtree(tmp, ignore_errors=True)
    shutil.copytree(os.path.join(T.set_dir(project), 'judge'), tmp)
    apply(tmp, q['judge_edits'])
    shutil.rmtree(d, ignore_errors=True)
    os.rename(tmp, d)


def tests_checking(project):
    """Reference test ids that fail when the reference holds a different value for the fact than the judge expects.
    Without a counterfactual judge: the reference judge, the reference with reference_variant applied. With one: the
    counterfactual judge, the unmodified reference (the variant must pass it in full). Returns (ids, verification)."""
    q = FEATURES[project]['questions']
    judge = q.get('judge') or 'judge'
    tmp = tree_copy(project)
    src = os.path.join(T.SRC, project)
    for m in T.meta_of(project)['modules']:
        shutil.copy2(os.path.join(src, m), os.path.join(tmp, m))
    real = T.score_tree(tmp, project, judge=judge)
    apply(tmp, q['reference_variant'])
    var = T.score_tree(tmp, project, judge=judge)
    shutil.rmtree(tmp, ignore_errors=True)
    ver = dict(judge=judge, reference=dict(unit_pass=real['unit_pass'], accept_pass=real['accept_pass']),
               reference_variant=dict(unit_pass=var['unit_pass'], accept_pass=var['accept_pass']))
    if q.get('judge'):
        assert var['unit_pass'] == 1.0 and var['accept_pass'] == 1.0, var
        return sorted(real['unit']['failed'] + real['accept']['failed']), ver
    assert real['unit_pass'] == 1.0 and real['accept_pass'] == 1.0, real
    return sorted(var['unit']['failed'] + var['accept']['failed']), ver


def contract_edits_check(project):
    c = FEATURES[project]['contracts']
    tmp = tree_copy(project)
    apply(tmp, [dict(file=c['file'], old=c['old'], new=c['new'])] + c['edits'])
    shutil.rmtree(tmp, ignore_errors=True)
    return True


def main():
    if len(sys.argv) > 1:
        sys.exit(__doc__)
    data = {}
    if os.path.exists(T.FEATURES):
        with open(T.FEATURES) as fh:
            data = json.load(fh)
    report, bad = {}, []
    for p, f in FEATURES.items():
        q = dict(f['questions'])
        if q.get('judge'):
            build_judge(p)
        hits = scrub_check(p)
        q['checked_by'], q['verification'] = tests_checking(p)
        q['scrub_check'] = dict(remaining=hits, ok=not hits)
        q.pop('reference_variant')
        if q.get('judge'):
            q['judge_dir'] = os.path.relpath(os.path.join(T.set_dir(p), q['judge']), T.SWARM)
        contract_edits_check(p)
        c = dict(f['contracts'])
        spec = C.INTERFACES[p]
        out, ok = C.verify(p)
        c['interface'] = spec['interface']
        c['provider'] = spec['provider']
        c['judges'] = dict(dir=os.path.relpath(os.path.join(T.set_dir(p), 'contracts'), T.SWARM),
                           interface_test=spec['test'][0],
                           how='score both judges per trial: dependent_old_pass / dependent_new_pass (agent dependents + '
                               'reference or adapted provider, base unit+accept tests), provider_old_pass / '
                               'provider_new_pass (agent provider, interface test of each version)',
                           verified={k: {x: v[x] for x in ('dependent_old_pass', 'dependent_new_pass',
                                                            'provider_old_pass', 'provider_new_pass')}
                                     for k, v in out.items()}, ok=ok)
        data[p] = dict(prd=f['prd'], questions=q, contracts=c)
        report[p] = dict(scrub_ok=not hits, checked_by=len(q['checked_by']), contracts_ok=ok)
        if hits or not ok or not q['checked_by']:
            bad.append(p)
    tmp = T.FEATURES + '.tmp'
    with open(tmp, 'w') as fh:
        json.dump(data, fh, indent=1, ensure_ascii=False)
        fh.write('\n')
    os.replace(tmp, T.FEATURES)
    print(json.dumps(report))
    sys.exit(f'failed: {bad}' if bad else 0)


if __name__ == '__main__':
    main()
